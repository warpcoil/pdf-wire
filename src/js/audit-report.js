/* ---------- report ---------- */
function reportInner() {
  const d = state.doc, e = count('error'), w = count('warning');
  const passed = state.results.filter((r) => r.status === 'pass' || r.status === 'na');
  const row = (f) => '<tr><td>' + (f.severity === 'error' ? 'Error' : 'Warning') + '</td><td>' + escHtml(f.title) +
    (f.detail ? '<br><span style="color:#4A5260">' + escHtml(f.detail) + '</span>' : '') + '</td><td>' + escHtml(criteriaText(f.rule)) + '</td><td>' +
    (f.page != null ? 'Page ' + (f.page + 1) : 'Document') + '</td></tr>';
  return '<p>' + escHtml(state.fileName) + ', checked ' + escHtml(new Date().toLocaleString()) + ' against WCAG 2.2 AA and PDF/UA-1 rules.</p>' +
    '<p><strong>' + plural(e, 'error') + ', ' + plural(w, 'warning') + ', ' + plural(passed.length, 'rule') + ' passed.</strong> ' +
    (e ? 'This document does not conform.' : 'No automated errors were found; conformance also depends on the manual checks and on rules not yet checked.') + '</p>' +
    '<h3>Document</h3><div class="table-wrap"><table><tbody>' +
    '<tr><th scope="row">Title</th><td>' + escHtml(d.xmpTitle || d.infoTitle || 'Not set') + '</td></tr>' +
    '<tr><th scope="row">Language</th><td>' + escHtml(d.lang || 'Not set') + '</td></tr>' +
    '<tr><th scope="row">Tagged</th><td>' + (d.tagged ? 'Yes' : 'No') + '</td></tr>' +
    '<tr><th scope="row">Pages</th><td>' + d.pages + '</td></tr>' +
    '<tr><th scope="row">PDF/UA claim</th><td>' + (d.uaPart ? 'PDF/UA-' + escHtml(d.uaPart) : 'None') + '</td></tr>' +
    '</tbody></table></div>' +
    '<h3>Problems found</h3>' + (state.findings.length ? '<div class="table-wrap"><table><thead><tr><th scope="col">Severity</th><th scope="col">Problem</th><th scope="col">Criteria</th><th scope="col">Where</th></tr></thead><tbody>' + state.findings.map(row).join('') + '</tbody></table></div>' : '<p>None found by the automated rules.</p>') +
    '<h3>Rules passed</h3><ul>' + passed.map((r) => '<li>' + escHtml(r.rule.title) + (r.status === 'na' ? ' (nothing to check)' : '') + '</li>').join('') + '</ul>' +
    '<h3>Manual checks</h3><ul>' + MANUAL.map((m) => '<li>' + (state.manual[m.id] ? 'Confirmed: ' : 'Not yet confirmed: ') + escHtml(m.text) + ' (' + m.wcag + ')</li>').join('') + '</ul>' +
    '<h3>Not checked by this version</h3><ul>' + NOT_CHECKED.map(([t, wc]) => '<li>' + escHtml(t) + (wc ? ' (' + wc + ')' : '') + '</li>').join('') + '</ul>' +
    '<p style="color:#4A5260">Generated by Accessible PDF Editor (test build 5). This report is not a conformance claim.</p>';
}
function reportDocument() {
  return '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">' +
    '<title>Accessibility report: ' + escHtml(state.fileName) + '</title><style>body{font:15px/1.5 system-ui,sans-serif;max-width:900px;margin:32px auto;padding:0 20px;color:#16181D}' +
    'table{border-collapse:collapse;width:100%}th,td{border-bottom:1px solid #D5D9DE;padding:7px 8px;text-align:left;vertical-align:top}th{color:#4A5260}</style></head><body>' +
    '<h1>Accessibility report: ' + escHtml(state.fileName) + '</h1>' + reportInner() + '</body></html>';
}
let downloads = null;
(async () => {
  try { if (window.claude && typeof window.claude.use === 'function') downloads = await window.claude.use('downloads'); } catch (e) { downloads = null; }
  $('#downloadReport').hidden = !downloads;
})();
function openReport() {
  $('#reportBody').innerHTML = reportInner();
  $('#reportTitle').textContent = 'Accessibility report: ' + clip(state.fileName, 50);
  $('#downloadNote').textContent = '';
  $('#downloadReport').hidden = !downloads;
  $('#reportDialog').showModal();
}
async function downloadReport() {
  if (!downloads) return;
  const name = state.fileName.replace(/\.pdf$/i, '') + '-accessibility-report.html';
  try { await downloads.save({ filename: name, data: reportDocument() }); $('#downloadNote').textContent = 'Report saved.'; }
  catch (e) {
    const code = e && e.code;
    $('#downloadNote').textContent = code === 'declined' ? 'Download cancelled.' : code === 'rate_limited' ? 'A download is already waiting for confirmation.' : 'Downloads are not available here.';
    if (code === 'unavailable' || code === 'not_granted' || code === 'capability_disabled' || code === 'capability_removed') $('#downloadReport').hidden = true;
  }
}

